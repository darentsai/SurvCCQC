#--- Survival Outcome ---#

# Add the last followup date "2021-12-31" for those who had not died
trans_date <- function(x) {
  x <- as.character(x)
  yyyy <- substr(x, 1, 4)
  mmdd <- substr(x, 5, 8)
  mmdd[mmdd == "9999"] <- "0701"
  mm <- substr(mmdd, 1, 2)
  mm[mm == "99"] <- "06"
  dd <- substr(mmdd, 3, 4)
  dd[dd == "99"] <- "15"
  as.Date(paste(yyyy, mm, dd, sep = "-"), format = "%Y-%m-%d")
}

